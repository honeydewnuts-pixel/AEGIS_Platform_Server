"""
Build v3 frame-dict history from features_v2.csv and run it through the
REAL production code:
  - app.services.signal_rule_engine_v3.SignalRuleEngineV3  (labels)
  - app.services.neural_features_v3.extract_feature_vector (features)

This guarantees the training data is generated by the exact same code
that will run in production, not a re-implementation that could drift
from it.
"""
import sys, json
sys.path.insert(0, "/home/claude/aegis_server/AEGIS_Platform_Server-main/backend")

import numpy as np
import pandas as pd

from app.services.signal_rule_engine_v3 import SignalRuleEngineV3
from app.services.neural_features_v3 import extract_feature_vector, FEATURE_DIM, HISTORY_WINDOW

df = pd.read_csv("/home/claude/pipeline/features_v2.csv").reset_index(drop=True)


def row_to_frame(row) -> dict:
    return {
        "price_band7": {"U": row.p7_U, "M": row.p7_M, "L": row.p7_L},
        "price_band8": {"U": row.p8_U, "M": row.p8_M, "L": row.p8_L},
        # negate real OCR values to match the pixel-Y "smaller=higher" convention
        # used throughout signal_rule_engine_v3.py / neural_features_v3.py
        "rsi6": -row.rsi6_val,
        "ma4": -row.ma4_val,
        "band1": {"U": -row.b1_U_val, "M": -row.b1_M_val, "L": -row.b1_L_val},
    }


frames = [row_to_frame(r) for r in df.itertuples()]

engine = SignalRuleEngineV3()
labels, rule_names, reasons = [], [], []
feature_rows = []

for i in range(len(frames)):
    history = frames[: i + 1]  # oldest ... current, exactly what evaluate()/extract_feature_vector() expect
    result = engine.evaluate(history)
    labels.append(result.signal or "HOLD")
    rule_names.append(result.rule_name)
    reasons.append(result.reason)

    feats = extract_feature_vector(history)
    feature_rows.append(feats["vector"])

feature_arr = np.asarray(feature_rows, dtype=np.float64)
assert feature_arr.shape[1] == FEATURE_DIM

out_df = df.copy()
out_df["LABEL"] = labels
out_df["RULE_NAME"] = rule_names
out_df["REASON"] = reasons

out_df.to_csv("/home/claude/pipeline/labeled_v3_production.csv", index=False)
np.save("/home/claude/pipeline/feature_matrix_v3.npy", feature_arr)

print("Label counts:\n", out_df["LABEL"].value_counts())
print("\nRule name counts:\n", out_df["RULE_NAME"].value_counts())
print("\nFeature matrix shape:", feature_arr.shape)
print("\nSample fired rows:")
print(out_df[out_df["LABEL"] != "HOLD"][["ts", "LABEL", "RULE_NAME"]].to_string())
